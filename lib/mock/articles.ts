import type { Article } from "@/lib/types";

function img(id: number, w = 800, h = 450) {
  return `https://picsum.photos/id/${id}/${w}/${h}`;
}

type Seed = {
  id: string;
  category: string;
  title: string;
  excerpt: string;
  heading: string;
  quote: string;
  pic: number;
  date: string;
  featured?: boolean;
  gallery?: boolean;
};

function buildDescription(seed: Seed): string {
  return `<p>تابعت منارة التطورات المرتبطة بموضوع «${seed.title}»، حيث تواصلت الجهات المعنية مع الرأي العام وقدّمت إحاطات متتابعة حول ما جرى على الأرض خلال الساعات الماضية.</p>
<p>${seed.excerpt} ويأتي هذا الاهتمام في سياق تغطية أوسع تسعى إلى وضع الحدث في إطاره المحلي والإقليمي دون مبالغة أو اختزال.</p>
<h2>${seed.heading}</h2>
<p>ويشير متابعون إلى أن المرحلة المقبلة ستتطلب تنسيقاً أوضح بين المؤسسات المعنية، مع الإبقاء على قنوات التواصل مفتوحة أمام الجمهور وتوثيق التفاصيل الدقيقة أولاً بأول.</p>
<blockquote>${seed.quote}</blockquote>
<p>وتستمر المتابعة عبر غرفة أخبار منارة، على أن تُحدَّث هذه المادة فور ورود معلومات إضافية مؤكدة من مصادرها.</p>`;
}

function fromSeed(seed: Seed): Article {
  return {
    id: seed.id,
    category: seed.category,
    title: seed.title,
    excerpt: seed.excerpt,
    description: buildDescription(seed),
    thumbnail: img(seed.pic, 480, 300),
    mainImage: img(seed.pic, 1200, 675),
    images: seed.gallery
      ? [img(seed.pic + 1, 900, 600), img(seed.pic + 2, 900, 600), img(seed.pic + 3, 900, 600)]
      : undefined,
    date: seed.date,
    featured: seed.featured,
  };
}

